"""Install a desktop launcher in the user's own directories (no sudo, no repo writes).

    vacuum_gui_install_desktop          # writes ~/.local/bin + ~/.local/share/applications
    vacuum_gui_install_desktop --uninstall
"""

import argparse
import os
import sys
from pathlib import Path

from . import paths

WRAPPER = """#!/bin/bash
# Generated by vacuum_gui_install_desktop: a login shell so ROS is sourced the way your
# terminal has it, then the system Python (a venv would shadow the ROS nodes' python3).
set +u
[ -f /opt/ros/{distro}/setup.bash ] && source /opt/ros/{distro}/setup.bash
[ -f "{ws}/install/setup.bash" ] && source "{ws}/install/setup.bash"
set -u
export PATH=/usr/bin:/bin:$PATH
exec ros2 run vacuum_gui vacuum_gui "$@"
"""

DESKTOP = """[Desktop Entry]
Type=Application
Name=RoboVAC Control Panel
GenericName=Robot vacuum simulation panel
Comment=Start the RoboVAC simulation, watch map, camera and health, run missions
Exec={exec_path}
Icon={icon_path}
Terminal=false
Categories=Robotics;Science;Utility;
StartupNotify=true
StartupWMClass=vacuum_gui
"""


def wrapper_path():
    return Path(os.path.expanduser('~/.local/bin/vacuum_gui'))


def alias_path():
    return Path(os.path.expanduser('~/.local/bin/vacuum_gui_launch'))


def desktop_path():
    return Path(os.path.expanduser('~/.local/share/applications/vacuum_gui.desktop'))


def icon_path():
    return Path(os.path.expanduser(
        '~/.local/share/icons/hicolor/scalable/apps/vacuum_gui.svg'))


def wrapper_text(ws, distro='jazzy'):
    return WRAPPER.format(ws=ws, distro=distro)


def desktop_text(exec_path, icon):
    return DESKTOP.format(exec_path=exec_path, icon_path=icon)


def install(ws=None, distro=None):
    ws = str(ws or paths.workspace_root())
    distro = distro or os.environ.get('ROS_DISTRO', 'jazzy')
    wrapper = wrapper_path()
    entry = desktop_path()
    icon = icon_path()
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    entry.parent.mkdir(parents=True, exist_ok=True)
    icon.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(wrapper_text(ws, distro))
    wrapper.chmod(0o755)
    alias = alias_path()
    try:
        if alias.is_symlink() or alias.exists():
            alias.unlink()
        alias.symlink_to(wrapper)
    except OSError:
        alias.write_text(wrapper_text(ws, distro))
        alias.chmod(0o755)
    source_icon = Path(__file__).resolve().parent.parent / 'assets' / 'vacuum_gui.svg'
    if source_icon.is_file():
        icon.write_text(source_icon.read_text())
    entry.write_text(desktop_text(str(wrapper), str(icon)))
    return wrapper, entry, icon


def uninstall():
    removed = []
    for path in (alias_path(), wrapper_path(), desktop_path(), icon_path()):
        try:
            path.unlink()
            removed.append(path)
        except OSError:
            pass
    return removed


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog='vacuum_gui_install_desktop',
        description='Install (or remove) the desktop launcher for the control panel.')
    parser.add_argument('--uninstall', action='store_true')
    parser.add_argument('--workspace', default=None,
                        help='colcon workspace root (default: detected)')
    args = parser.parse_args(argv)
    if args.uninstall:
        for path in uninstall():
            print('removed %s' % path)
        return 0
    wrapper, entry, icon = install(args.workspace)
    print('launcher : %s' % wrapper)
    print('desktop  : %s' % entry)
    print('icon     : %s' % icon)
    print('\nIf the entry does not show up: gtk-launch vacuum_gui   '
          '(or log out and back in)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
